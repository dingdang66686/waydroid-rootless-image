#!/usr/bin/env bash
#
# build.sh - build the layered images that run.sh can boot directly:
#
#   localhost/waydroid-base:13      ./rootfs as an OCI image (podman import)
#   localhost/waydroid-tweaked:13   base + the rootless runtime overrides
#   localhost/waydroid-arm64:13     tweaked + the libndk ARM translation layer
#
# Usage:  ./build.sh [all|base|tweaked|arm]
#
#   WD_ROOTFS=...          directory to import        (./rootfs)
#   WD_BASE_IMAGE=...      name of the imported image (localhost/waydroid-base:13)
#   WD_TWEAKED_IMAGE=...   (localhost/waydroid-tweaked:13)
#   WD_ARM_IMAGE=...       (localhost/waydroid-arm64:13)
#
# Boot one with
#
#   WD_ROOTFS_IMAGE=localhost/waydroid-arm64:13 ./run.sh -d
#
# No root and no registry access is needed: podman's rootless storage and
# rootfs are the only inputs, plus image/prebuilts for the ARM layer.
#
# Why the modified files are derived here and not in the Containerfile:
# the Android rootfs cannot execute anything before init has mounted the
# flattened APEXes (/system/bin/sh's interpreter lives in
# /apex/com.android.runtime/bin/), so the image has no usable RUN.  See the
# header of image/Containerfile.
#
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

ROOTFS="${WD_ROOTFS:-$HERE/rootfs}"
PREBUILTS="$HERE/prebuilts"
BASE_IMAGE="${WD_BASE_IMAGE:-localhost/waydroid-base:13}"
TWEAKED_IMAGE="${WD_TWEAKED_IMAGE:-localhost/waydroid-tweaked:13}"
ARM_IMAGE="${WD_ARM_IMAGE:-localhost/waydroid-arm64:13}"

# build/ is generated by this script and is the Containerfile's build context.
STAGE="$HERE/build"
TWEAKS="$STAGE/tweaks"
ARMPROPS="$STAGE/armprops"

ZygoteRC="system/etc/init/hw/init.zygote64_32.rc"
KeychordRC="system/system_ext/etc/init/init.lineage-system_ext.rc"
BpfloaderRC="system/etc/init/bpfloader.rc"
PropFiles=(
    "system/build.prop"
    "vendor/build.prop"
    "vendor/odm/etc/build.prop"
)

say() { printf '[image] %s\n' "$*" >&2; }

need_rootfs() {
    [[ -e "$ROOTFS/system/build.prop" ]] ||
        { echo "no rootfs at $ROOTFS; run ./extract.sh first" >&2; exit 1; }
}

# The rootfs is extracted by an unprivileged user, so the ownership and the
# group bits of the files that were only group-accessible in the original
# images are lost.  run.sh papers over that by chmod'ing the pristine tree on
# every run; the image needs the same fix, applied once, before it is tarred.
fix_perms() {
    say "fixing up world-read permissions under $ROOTFS"
    find "$ROOTFS" -xdev -type f ! -perm -o=r -exec chmod a+rX {} +
    find "$ROOTFS" -xdev -type d ! -perm -o=x -exec chmod a+X {} +
}

build_base() {
    need_rootfs
    fix_perms
    say "podman import $ROOTFS -> $BASE_IMAGE"
    # --owner=0 --group=0: everything in the image is owned by root, exactly
    # like the "rootfs dir + derived userns" case, where the unprivileged
    # extraction owner maps to uid 0 inside the container.
    tar --numeric-owner --owner=0 --group=0 --sort=name -C "$ROOTFS" -cf - . |
        podman import - "$BASE_IMAGE" >/dev/null
    say "$BASE_IMAGE: $(podman image inspect -f '{{.Id}}' "$BASE_IMAGE")"
}

stage_files() {
    need_rootfs
    rm -rf "$STAGE"
    mkdir -p \
        "$TWEAKS/$(dirname "$ZygoteRC")" \
        "$TWEAKS/$(dirname "$KeychordRC")" \
        "$TWEAKS/$(dirname "$BpfloaderRC")"
    for f in "${PropFiles[@]}"; do mkdir -p "$ARMPROPS/$(dirname "$f")"; done

    # ---- rootless runtime overrides (the files run.sh used to bind in) ----
    #
    # bpfloader: init's bpfloader loads /system/etc/bpf/*.o and then sets
    # bpf.progs_loaded=1.  A rootless container cannot load eBPF (no
    # CAP_BPF/CAP_SYS_ADMIN in the initial userns), so publish the property the
    # rest of the tree waits for instead.
    cat > "$TWEAKS/$BpfloaderRC" <<'EOF'
# installed by waydroid-rootless/image/build.sh: a rootless container cannot
# load eBPF, so do not run the loader -- just publish the property (and the
# attached programs) its consumers wait for.
on load_bpf_programs
    setprop bpf.progs_loaded 1
EOF

    # zygote: "priority -20" needs CAP_SYS_NICE in the *initial* user
    # namespace.  init fatals out when a process attribute cannot be applied,
    # so drop the line (both zygotes are started from this file).
    sed -E '/^[[:space:]]*priority[[:space:]]+-[0-9]+[[:space:]]*$/d' \
        "$ROOTFS/$ZygoteRC" > "$TWEAKS/$ZygoteRC"

    # keychords: the LineageOS addition opens /dev/hwcomposer-style fifos for
    # keychord detection; rootless the open blocks forever.  Drop the lines.
    sed -E '/^[[:space:]]*keycodes([[:space:]]|$)/d' \
        "$ROOTFS/$KeychordRC" > "$TWEAKS/$KeychordRC"

    # ---- ARM translation layer properties -------------------------------
    #
    # The native bridge is enabled purely through "ro." properties, and those
    # are write-once: a later waydroid.prop cannot fix a value that build.prop
    # already set.  So the three partition build.props are patched in place and
    # the missing keys are appended (they are all "ro.system.product.*" /
    # "ro.vendor.product.*" / "ro.odm.product.*" -- init derives the plain
    # "ro.product.cpu.abilist" family from them, and both spellings end up with
    # the same value here).
    local abi_full="x86_64,x86,arm64-v8a,armeabi-v7a,armeabi"
    local abi_32="x86,armeabi-v7a,armeabi"
    local abi_64="x86_64,arm64-v8a"
    local f
    for f in "${PropFiles[@]}"; do
        sed -E \
            -e "s/^(ro\.(system|vendor|odm)\.product\.cpu\.abilist)=.*/\1=$abi_full/" \
            -e "s/^(ro\.(system|vendor|odm)\.product\.cpu\.abilist32)=.*/\1=$abi_32/" \
            -e "s/^(ro\.(system|vendor|odm)\.product\.cpu\.abilist64)=.*/\1=$abi_64/" \
            -e "s/^(ro\.dalvik\.vm\.native\.bridge)=.*/\1=libndk_translation.so/" \
            "$ROOTFS/$f" > "$ARMPROPS/$f"
    done
    cat >> "$ARMPROPS/system/build.prop" <<EOF

# ---- libndk_translation (ARM native bridge) ----
# Added by waydroid-rootless/image/build.sh.  Values match waydroid_script's
# NDK package (stuff/ndk.py), which installs Google's ndk_translation prebuilt.
ro.product.cpu.abilist=$abi_full
ro.product.cpu.abilist32=$abi_32
ro.product.cpu.abilist64=$abi_64
ro.dalvik.vm.native.bridge=libndk_translation.so
ro.enable.native.bridge.exec=1
ro.vendor.enable.native.bridge.exec=1
ro.vendor.enable.native.bridge.exec64=1
ro.ndk_translation.version=0.2.3
ro.dalvik.vm.isa.arm=x86
ro.dalvik.vm.isa.arm64=x86_64
EOF
    say "staged $(find "$TWEAKS" -type f | wc -l) tweak files and ${#PropFiles[@]} prop files"
}

check_prebuilts() {
    [[ -d "$PREBUILTS" ]] ||
        { echo "no $PREBUILTS; run ./fetch-prebuilts.sh first" >&2; exit 1; }
    if [[ -f "$HERE/prebuilts.sha256" ]]; then
        say "verifying prebuilts.sha256"
        ( cd "$PREBUILTS" && sha256sum -c --quiet "$HERE/prebuilts.sha256" ) ||
            { echo "prebuilts/ does not match prebuilts.sha256" >&2; exit 1; }
    fi
}

build_images() {
    local targets=("$@") t
    for t in "${targets[@]}"; do
        case "$t" in
        tweaked) say "podman build --target tweaked -t $TWEAKED_IMAGE"; podman build \
            --target tweaked -t "$TWEAKED_IMAGE" "$HERE" ;;
        arm) check_prebuilts
             say "podman build --target arm -t $ARM_IMAGE"; podman build \
            --target arm -t "$ARM_IMAGE" "$HERE" ;;
        *) echo "unknown target: $t" >&2; exit 1 ;;
        esac
    done
}

case "${1:-all}" in
base)    build_base ;;
tweaked) stage_files; build_images tweaked ;;
arm)     stage_files; build_images tweaked arm ;;
all)     build_base; stage_files; build_images tweaked arm ;;
*)       echo "usage: $0 [all|base|tweaked|arm]" >&2; exit 1 ;;
esac

say "done; boot with WD_ROOTFS_IMAGE=$ARM_IMAGE ./run.sh -d"
